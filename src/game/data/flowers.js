// ID ile çiçek bul
export const cicekBul = (id) => CICEKLER.find(c => c.id === id);

// Mevsimine göre çiçekleri filtrele
export const mevsimeCicekleri = (mevsim) =>
  CICEKLER.filter(c => c.mevsimler.includes(mevsim) || c.mevsimler.includes('tümü'));

// Nadirliğe göre filtrele
export const nadirlikeCicekleri = (nadirlik) =>
  CICEKLER.filter(c => c.nadirlik === nadirlik);

// Level'a göre mevcut çiçekler
export const leveleCicekleri = (level) =>
  CICEKLER.filter(c => c.kilidAcLevel <= level);
